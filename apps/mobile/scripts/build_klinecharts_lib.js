/**
 * Build script to generate klinecharts_lib.ts from the bundled klinecharts.min.txt
 * This avoids Metro asset resolution issues by inlining the library as a string constant
 */
const fs = require("fs");
const path = require("path");

const srcFile = path.join(__dirname, "..", "assets", "vendor", "klinecharts.min.txt");
const outFile = path.join(__dirname, "klinecharts_lib.ts");

const content = fs.readFileSync(srcFile, "utf-8");

// Escape backticks and backslashes for template literal
const escaped = content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const output = `// Auto-generated by build_klinecharts_lib.js - DO NOT EDIT
// Source: assets/vendor/klinecharts.min.txt (${content.length} bytes)

export const KLINECHARTS_LIB = \`${escaped}\`;
`;

fs.writeFileSync(outFile, output, "utf-8");
console.log(`Generated ${outFile} (${output.length} bytes)`);
